document.addEventListener('DOMContentLoaded', () => {
    // 1. Retrieve brand ID from query parameter (?brand=...)
    const params = new URLSearchParams(window.location.search);
    let brandId = params.get('brand') || 'katakita';
    if (!BRAND_DATABASE[brandId]) {
        brandId = 'katakita';
    }

    const brand = BRAND_DATABASE[brandId];

    // 2. Populate Page Title and Metadata
    document.title = `${brand.name} | Rangga Portfolio`;
    const titleEl = document.getElementById('page-title');
    if (titleEl) titleEl.textContent = `${brand.name} | Rangga Portfolio`;

    const nameEl = document.getElementById('brand-name');
    if (nameEl) nameEl.textContent = brand.name;

    const taglineEl = document.getElementById('brand-tagline');
    if (taglineEl) taglineEl.textContent = brand.tagline;

    const industryEl = document.getElementById('brand-industry');
    if (industryEl) {
        industryEl.innerHTML = `<i class="ph-fill ph-tag"></i> ${brand.industry}`;
    }

    const logoEl = document.getElementById('brand-logo');
    if (logoEl) {
        logoEl.src = brand.logo;
        logoEl.alt = `${brand.name} Logo`;
    }

    // 3. Field, Role, Timeline, and Narrative Summary
    const metaFieldEl = document.getElementById('brand-meta-field');
    if (metaFieldEl) metaFieldEl.textContent = brand.field || brand.industry;

    const roleEl = document.getElementById('brand-role');
    if (roleEl) roleEl.textContent = brand.role;

    const timelineLocEl = document.getElementById('brand-timeline-loc');
    if (timelineLocEl) timelineLocEl.textContent = `${brand.timeline} • ${brand.location}`;

    const descEl = document.getElementById('brand-desc');
    if (descEl) descEl.textContent = brand.desc;

    // 4. Render Works Grid
    const galleryGrid = document.getElementById('brand-works-grid');
    if (galleryGrid) {
        if (brand.gallery && brand.gallery.length > 0) {
            galleryGrid.innerHTML = brand.gallery.map((item, idx) => `
                <div class="brand-work-card ${item.type === 'video' ? 'brand-work-card--video' : ''}" data-idx="${idx}">
                    <div class="work-media-wrapper">
                        ${item.type === 'video' && item.videoType === 'local' ? `
                            <video class="work-card-media-video" src="${item.videoSrc}#t=0.5" preload="metadata" muted playsinline loop></video>
                        ` : `
                            <img src="${item.src}" alt="${item.title}" loading="lazy" onerror="this.src='${item.fallback || item.src}'">
                        `}
                        ${item.type === 'video' ? `
                            <div class="work-video-badge">
                                <i class="ph-fill ${item.videoType === 'youtube' ? 'ph-youtube-logo' : 'ph-play'}"></i>
                                <span>${item.videoType === 'youtube' ? 'YouTube Showcase' : 'Video & Motion'}</span>
                            </div>
                        ` : ''}
                        <div class="work-hover-overlay">
                            <span><i class="ph-fill ${item.type === 'video' ? 'ph-play' : 'ph-arrows-out'}"></i> ${item.type === 'video' ? 'Watch Full Video' : 'Fullscreen Preview'}</span>
                        </div>
                    </div>
                    <div class="work-card-info">
                        <span class="work-card-tag">${item.meta}</span>
                        <h3>${item.title}</h3>
                        <p>${item.caption}</p>
                    </div>
                </div>
            `).join('');
        } else {
            galleryGrid.innerHTML = `
                <div class="brand-assets-pending-card">
                    <div class="pending-icon-wrap">
                        <i class="ph-bold ph-image-square"></i>
                    </div>
                    <div class="pending-content">
                        <span class="pending-badge"><i class="ph-fill ph-folder-notch-open"></i> Assets Pending Upload</span>
                        <h3>Curated Brand Visuals Pending Upload</h3>
                        <p>High-resolution project photography and motion assets will be loaded from <code>assets/images/${brand.folderName || brand.id}/</code>.</p>
                        <div class="pending-checklist">
                            <div class="pending-step"><i class="ph-fill ph-check-circle"></i> Brand Strategy & Direction Configured</div>
                            <div class="pending-step"><i class="ph-fill ph-check-circle"></i> Showcase Grid Prepared for Media</div>
                            <div class="pending-step"><i class="ph-bold ph-clock"></i> Ready for photo & video uploads</div>
                        </div>
                    </div>
                </div>
            `;
        }
    }

    // 5. Lightbox Modal
    const lightboxModal = document.getElementById('lightbox-modal');
    const lightboxImg = document.getElementById('lightbox-img');
    const lightboxVideo = document.getElementById('lightbox-video');
    const lightboxIframe = document.getElementById('lightbox-iframe');
    const lightboxExternalCta = document.getElementById('lightbox-external-cta');
    const lightboxTitle = document.getElementById('lightbox-title');
    const lightboxSubtitle = document.getElementById('lightbox-subtitle');
    const lightboxClose = document.getElementById('lightbox-close');
    const lightboxBackdrop = document.getElementById('lightbox-backdrop');

    const openLightbox = (idx) => {
        if (!brand.gallery || !brand.gallery[idx]) return;
        const item = brand.gallery[idx];
        if (!lightboxModal) return;

        // Pause any card hover previews
        if (galleryGrid) {
            galleryGrid.querySelectorAll('video.work-card-media-video').forEach(v => v.pause());
        }

        if (lightboxTitle) lightboxTitle.textContent = item.title;
        if (lightboxSubtitle) lightboxSubtitle.textContent = item.caption;
        if (lightboxExternalCta) lightboxExternalCta.innerHTML = '';

        if (item.type === 'video') {
            if (item.videoType === 'youtube') {
                if (lightboxImg) lightboxImg.style.display = 'none';
                if (lightboxVideo) {
                    lightboxVideo.style.display = 'none';
                    lightboxVideo.pause();
                    lightboxVideo.src = '';
                }
                if (lightboxIframe) {
                    lightboxIframe.style.display = 'block';
                    lightboxIframe.src = `https://www.youtube-nocookie.com/embed/${item.youtubeId}?autoplay=1&rel=0`;
                }
                if (lightboxExternalCta && item.youtubeUrl) {
                    lightboxExternalCta.innerHTML = `
                        <a href="${item.youtubeUrl}" target="_blank" rel="noopener noreferrer" class="btn-lightbox-yt">
                            <i class="ph-fill ph-youtube-logo"></i> Watch on YouTube ↗
                        </a>
                    `;
                }
            } else {
                // Local video
                if (lightboxImg) lightboxImg.style.display = 'none';
                if (lightboxIframe) {
                    lightboxIframe.style.display = 'none';
                    lightboxIframe.src = '';
                }
                if (lightboxVideo) {
                    lightboxVideo.style.display = 'block';
                    lightboxVideo.src = item.videoSrc;
                    lightboxVideo.play().catch(() => {});
                }
            }
        } else {
            // Photo
            if (lightboxVideo) {
                lightboxVideo.style.display = 'none';
                lightboxVideo.pause();
                lightboxVideo.src = '';
            }
            if (lightboxIframe) {
                lightboxIframe.style.display = 'none';
                lightboxIframe.src = '';
            }
            if (lightboxImg) {
                lightboxImg.style.display = 'block';
                lightboxImg.src = item.src;
                lightboxImg.onerror = () => { lightboxImg.src = item.fallback || item.src; };
            }
        }

        lightboxModal.classList.add('is-open');
        lightboxModal.setAttribute('aria-hidden', 'false');
        document.body.style.overflow = 'hidden';
    };

    const closeLightbox = () => {
        if (!lightboxModal) return;
        lightboxModal.classList.remove('is-open');
        lightboxModal.setAttribute('aria-hidden', 'true');
        document.body.style.overflow = '';

        // Stop playback
        if (lightboxVideo) {
            lightboxVideo.pause();
            lightboxVideo.src = '';
            lightboxVideo.style.display = 'none';
        }
        if (lightboxIframe) {
            lightboxIframe.src = '';
            lightboxIframe.style.display = 'none';
        }
        if (lightboxImg) {
            lightboxImg.style.display = 'block';
            lightboxImg.src = '';
        }
        if (lightboxExternalCta) {
            lightboxExternalCta.innerHTML = '';
        }
    };

    // Card click and live hover preview listeners
    if (galleryGrid) {
        galleryGrid.querySelectorAll('.brand-work-card').forEach(card => {
            const idx = parseInt(card.getAttribute('data-idx'), 10);
            card.addEventListener('click', () => {
                openLightbox(idx);
            });

            // Live hover preview & instant frame rendering for local videos
            const previewVideo = card.querySelector('video.work-card-media-video');
            if (previewVideo) {
                const setFrame = () => {
                    if (previewVideo.currentTime === 0) {
                        previewVideo.currentTime = 0.5;
                    }
                };

                if (previewVideo.readyState >= 1) {
                    setFrame();
                } else {
                    previewVideo.addEventListener('loadedmetadata', setFrame, { once: true });
                }

                card.addEventListener('mouseenter', () => {
                    previewVideo.play().catch(() => {});
                });

                card.addEventListener('mouseleave', () => {
                    previewVideo.pause();
                    previewVideo.currentTime = 0.5;
                });
            }
        });
    }

    if (lightboxClose) lightboxClose.addEventListener('click', closeLightbox);
    if (lightboxBackdrop) lightboxBackdrop.addEventListener('click', closeLightbox);
    document.addEventListener('keydown', (e) => {
        if (e.key === 'Escape') closeLightbox();
    });

    // 6. Other Brands Switcher
    const switchGrid = document.getElementById('brand-switch-grid');
    if (switchGrid) {
        const allBrands = Object.values(BRAND_DATABASE);
        switchGrid.innerHTML = allBrands.map(b => `
            <a href="brand.html?brand=${b.id}" class="brand-switch-card ${b.id === brandId ? 'active' : ''}" title="View ${b.name} showcase">
                <div class="switch-card-logo">
                    <img src="${b.logo}" alt="${b.name} Logo" loading="lazy">
                </div>
                <div class="switch-card-text">
                    <strong>${b.name}</strong>
                    <span>${b.industry}</span>
                </div>
                <span class="switch-card-cta">View ↗</span>
            </a>
        `).join('');
    }

    // 7. Custom Cursor
    const cursor = document.querySelector('.custom-cursor');
    if (cursor) {
        let isCursorVisible = false;
        document.addEventListener('mousemove', (e) => {
            if (!isCursorVisible) {
                cursor.classList.add('visible');
                isCursorVisible = true;
            }
            cursor.style.left = e.clientX + 'px';
            cursor.style.top = e.clientY + 'px';
        });
        document.addEventListener('mouseleave', () => {
            cursor.classList.remove('visible');
            isCursorVisible = false;
        });
        document.addEventListener('mouseenter', () => {
            cursor.classList.add('visible');
            isCursorVisible = true;
        });
        document.addEventListener('mousedown', () => cursor.classList.add('clicking'));
        document.addEventListener('mouseup', () => cursor.classList.remove('clicking'));

        document.addEventListener('mouseover', (e) => {
            if (e.target.closest('a, button, [role="button"], input, select, textarea, .brand-work-card, .brand-switch-card, .dock-btn')) {
                cursor.classList.add('hover');
            }
        });
        document.addEventListener('mouseout', (e) => {
            if (e.target.closest('a, button, [role="button"], input, select, textarea, .brand-work-card, .brand-switch-card, .dock-btn')) {
                cursor.classList.remove('hover');
            }
        });
    }
});
